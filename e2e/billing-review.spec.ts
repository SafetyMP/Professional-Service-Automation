import { expect, test } from "@playwright/test";

test("fixed-fee case reconciles the draft and compares pilot assumptions", async ({ page }) => {
  await page.goto("/case");
  const available = page.getByLabel("Available for a new draft", { exact: true });
  await expect(available).toHaveCount(0);
  await expect(page.getByRole("heading", { name: "Invoice register" })).toBeVisible();
  await expect(page.getByText("Client reference PO-418")).toBeVisible();
  await page.getByRole("button", { name: "Hold for review" }).click();
  await expect(available).toHaveText("$0");
  await expect(page.getByText("Cash received", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Restart with the open draft" }).click();
  await page.getByRole("button", { name: "Issue draft" }).click();
  await expect(available).toHaveText("$0");
  await expect(page.getByText("$24,000", { exact: true })).toHaveCount(2);
  await expect(page.getByRole("button", { name: "Void draft" })).toHaveCount(0);
  await page.getByRole("button", { name: "Restart with the open draft" }).click();
  await page.getByRole("button", { name: "Void draft" }).click();
  await expect(available).toHaveText("$6,000");
  const acceptance = page.getByLabel("Client acceptance record");
  await page.getByRole("button", { name: "Restart with the open draft" }).click();
  await acceptance.selectOption("50");
  await page.getByRole("button", { name: "Issue draft" }).click();
  await expect(available).toHaveText("$6,000");
  await page.getByRole("button", { name: "Restart with the open draft" }).click();
  await expect(acceptance).toHaveValue("50");
  await expect(available).toHaveCount(0);
  await page.getByRole("button", { name: "Void draft" }).click();
  await expect(available).toHaveText("$12,000");
  const net = page.getByLabel("First-year net capacity value");
  await expect(net).toHaveText("$600");
  await page.getByRole("slider", { name: /Minutes saved/ }).press("Home");
  await expect(net).toHaveText("-$2,400");
  await page.getByRole("button", { name: "Run a shadow pilot" }).click();
  await page.getByRole("link", { name: "Technical guide" }).click();
  await expect(page.getByRole("heading", { name: "Trace the billing decision" })).toBeVisible();
  await expect(page.locator("tbody tr").last()).toHaveText("Available for a new draft$12,000$6,000");
  await page.getByRole("button", { name: "Trial B · Void" }).click();
  await expect(page.locator("tbody tr").last()).toHaveText("Available for a new draft$12,000$12,000");
  await page.reload();
  await expect(page.getByRole("button", { name: "Trial B · Void" })).toHaveAttribute("aria-pressed", "true");
  const workedAnswer = page.getByText("At 40% acceptance,", { exact: false });
  await expect(workedAnswer).toBeHidden();
  await page.getByText("Worked answer · opening ledger and invoice references").click();
  await expect(workedAnswer).toBeVisible();
  await expect(page.locator('a[href="/login"]')).toHaveCount(0);
  await page.getByRole("link", { name: "Back to the billing case" }).click();
  await expect(available).toHaveText("$12,000");
  await expect(net).toHaveText("-$2,400");
  await expect(page.getByRole("button", { name: "Run a shadow pilot" })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("link", { name: "Trace the billing decision", exact: true }).click();
  await page.getByLabel("Evidence available through").selectOption("2026-07-24");
  await expect(page.locator("tbody tr").last()).toHaveText("Available for a new draft$6,000$12,000");
  await page.getByRole("link", { name: "Back to the billing case" }).click();
  await expect(acceptance).toHaveValue("40");
});

test("direct technical link restores the selected records and both halves of the study", async ({ page }) => {
  await page.goto("/case#docket");
  await expect(page.locator(":target").getByRole("heading", { name: "Warehouse redesign" })).toBeInViewport();
  await page.goto("/case#prebill");
  await expect(page.locator(":target").getByRole("button", { name: "Hold for review" })).toBeInViewport();
  await page.goto("/case/technical?progress=50&treatment=hold&reviews=12&minutes=20&choice=register&trial=voided");
  await expect(page.locator("tbody tr").last()).toHaveText("Available for a new draft$6,000$12,000");
  await page.getByRole("link", { name: "Back to the billing case" }).click();
  await expect(page.getByRole("button", { name: "Add a draft register" })).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByRole("slider", { name: /Monthly reviews/ })).toHaveValue("12");
  await expect(page.getByRole("slider", { name: /Minutes saved/ })).toHaveValue("20");
  await expect(page.getByLabel("Available for a new draft", { exact: true })).toHaveText("$6,000");
});
